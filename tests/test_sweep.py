"""The quiet sweep: transcript reading, watermarks, extraction gates, offers."""

import importlib.machinery
import importlib.util
import json
from pathlib import Path

CORE = Path(__file__).resolve().parents[1] / "bin" / "core"


def load_core():
    l = importlib.machinery.SourceFileLoader("core", str(CORE))
    m = importlib.util.module_from_spec(importlib.util.spec_from_loader("core", l))
    l.exec_module(m)
    return m


def write_transcript(path, entries):
    path.write_text("".join(json.dumps(e) + "\n" for e in entries))
    return path


def user(text, **kw):
    return dict({"type": "user", "message": {"role": "user", "content": text}, "timestamp": "2026-10-01T10:00:00Z"}, **kw)


def assistant(*blocks, **kw):
    return dict({"type": "assistant", "message": {"role": "assistant", "content": list(blocks)},
                 "timestamp": "2026-10-01T10:00:05Z"}, **kw)


def test_turns_keep_only_the_conversation(tmp_path):
    core = load_core()
    t = write_transcript(tmp_path / "s.jsonl", [
        {"type": "mode", "mode": "x"},
        user("<local-command-caveat>Caveat: generated by local commands</local-command-caveat>"),
        user("let's use SQLite, Postgres is overkill here"),
        assistant({"type": "thinking", "thinking": "secret reasoning"},
                  {"type": "text", "text": "Agreed, SQLite it is."},
                  {"type": "tool_use", "name": "Bash", "input": {"command": "ls"}}),
        user([{"type": "tool_result", "content": "file listing"}]),
        user("meta injection", isMeta=True),
        user("subagent prompt", isSidechain=True),
        assistant({"type": "text", "text": "Done."}),
        user([{"type": "text", "text": "no, never use emoji in commits"}]),
    ])
    turns = core.transcript_turns(t)
    assert [(r, x) for _, r, x in turns] == [
        ("user", "let's use SQLite, Postgres is overkill here"),
        ("assistant", "Agreed, SQLite it is.\nDone."),
        ("user", "no, never use emoji in commits"),
    ]
    assert turns[0][0] == 3  # line number in the transcript, for traceable quotes


