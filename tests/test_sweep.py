class FakeChat(BaseHTTPRequestHandler):
    reply = {"items": []}
    calls = []
    fail = False

    def do_POST(self):
        body = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
        FakeChat.calls.append(body)
        if FakeChat.fail:
            self.send_response(500); self.end_headers(); return
        out = json.dumps({"message": {"role": "assistant", "content": json.dumps(FakeChat.reply)}}).encode()
        self.send_response(200); self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(out))); self.end_headers(); self.wfile.write(out)

    def log_message(self, *a):
        pass


@pytest.fixture
def chat():
    FakeChat.reply, FakeChat.calls, FakeChat.fail = {"items": []}, [], False
    srv = HTTPServer(("127.0.0.1", 0), FakeChat)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    yield "http://127.0.0.1:{}".format(srv.server_port)
    srv.shutdown()


def setup_sweep(tmp_path, url, quiet_ago=3600):
    home = tmp_path / "home"
    proj = home / ".claude" / "projects" / "-x"
    proj.mkdir(parents=True)
    t = write_transcript(proj / "sess.jsonl", [
        user("let's use SQLite, Postgres is overkill here"),
        assistant({"type": "text", "text": "Agreed."}),
        user("and never use emoji in commit messages"),
        assistant({"type": "text", "text": "Noted."}),
    ])
    old = time.time() - quiet_ago
    os.utime(str(t), (old, old))
    h = tmp_path / "corehome"
    h.mkdir()
    (h / "recall.conf").write_text("sweep_model fake-llm\nsweep_url {}\n".format(url))
    return t


def run_core(tmp_path, *args):
    env = {"HOME": str(tmp_path / "home"), "CORE_HOME": str(tmp_path / "corehome"), "PATH": os.environ["PATH"]}
    return subprocess.run(["python3", str(CORE), *args], capture_output=True, text=True, env=env, timeout=60)


def test_sweep_offers_items_with_provenance_and_never_writes_memory(chat, tmp_path):
    t = setup_sweep(tmp_path, chat)
    FakeChat.reply = {"items": [{"type": "correction", "statement": "Never use emoji in commit messages.",
                                 "quote": "never use emoji in commit messages", "line": 99}]}
