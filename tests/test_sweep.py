"""The quiet sweep: transcript reading, watermarks, extraction gates, offers."""

import importlib.machinery
import importlib.util
import json
from pathlib import Path

CORE = Path(__file__).resolve().parents[1] / "bin" / "core"


def load_core():
    l = importlib.machinery.SourceFileLoader("core", str(CORE))
    m = importlib.util.module_from_spec(importlib.util.spec_from_loader("core", l))
    l.exec_module(m)
    return m


def write_transcript(path, entries):
    path.write_text("".join(json.dumps(e) + "\n" for e in entries))
    return path


def user(text, **kw):
    return dict({"type": "user", "message": {"role": "user", "content": text}, "timestamp": "2026-10-01T10:00:00Z"}, **kw)


def assistant(*blocks, **kw):
    return dict({"type": "assistant", "message": {"role": "assistant", "content": list(blocks)},
                 "timestamp": "2026-10-01T10:00:05Z"}, **kw)


def test_turns_keep_only_the_conversation(tmp_path):
    core = load_core()
    t = write_transcript(tmp_path / "s.jsonl", [
        {"type": "mode", "mode": "x"},
        user("<local-command-caveat>Caveat: generated by local commands</local-command-caveat>"),
        user("let's use SQLite, Postgres is overkill here"),
        assistant({"type": "thinking", "thinking": "secret reasoning"},
                  {"type": "text", "text": "Agreed, SQLite it is."},
                  {"type": "tool_use", "name": "Bash", "input": {"command": "ls"}}),
        user([{"type": "tool_result", "content": "file listing"}]),
        user("meta injection", isMeta=True),
        user("subagent prompt", isSidechain=True),
        assistant({"type": "text", "text": "Done."}),
        user([{"type": "text", "text": "no, never use emoji in commits"}]),
    ])
    turns = core.transcript_turns(t)
    assert [(r, x) for _, r, x in turns] == [
        ("user", "let's use SQLite, Postgres is overkill here"),
        ("assistant", "Agreed, SQLite it is.\nDone."),
        ("user", "no, never use emoji in commits"),
    ]
    assert turns[0][0] == 3  # line number in the transcript, for traceable quotes


def test_turns_survive_garbage_lines(tmp_path):
    core = load_core()
    t = tmp_path / "s.jsonl"
    t.write_text('not json\n{"type": "user"}\n' + json.dumps(user("real message")) + "\n")
    assert [x for _, _, x in core.transcript_turns(t)] == ["real message"]


def test_hook_injected_context_is_not_the_person(tmp_path):
    core = load_core()
    t = write_transcript(tmp_path / "s.jsonl", [
        user("<system-reminder>recall lines</system-reminder>"),
        user("<command-name>/clear</command-name>"),
        user("Another Claude session sent a message: report"),
        user("ship it on thursday"),
    ])
    assert [x for _, _, x in core.transcript_turns(t)] == ["ship it on thursday"]


TURNS = [(3, "user", "let's use SQLite, Postgres is overkill here"),
         (4, "assistant", "Agreed. Should we also add Redis?"),
         (7, "user", "maybe we could add Redis later, not sure"),
         (9, "user", "no, never use emoji in commits")]


def test_gate_keeps_only_verbatim_quotes_from_the_person():
    core = load_core()
    items = [
        {"type": "decision", "statement": "Logan chose SQLite over Postgres.", "quote": "let's use SQLite", "line": 3},
        {"type": "decision", "statement": "Redis will be added.", "quote": "Should we also add Redis?", "line": 4},  # assistant's words
        {"type": "decision", "statement": "Logan chose MySQL.", "quote": "let's use MySQL", "line": 3},  # not said
        {"type": "correction", "statement": "Never use emoji in commit messages.", "quote": "never use emoji in  commits", "line": 9},
    ]
    kept = core.sweep_gate(items, TURNS)
    assert [k["statement"] for k in kept] == ["Logan chose SQLite over Postgres.", "Never use emoji in commit messages."]
    assert kept[1]["line"] == 9  # line comes from where the quote really is


def test_gate_drops_hypotheticals_and_questions():
    # "He didn't say no" is not "he said yes": a maybe is never a decision.
    core = load_core()
    items = [{"type": "decision", "statement": "Redis will be added later.", "quote": "maybe we could add Redis later", "line": 7}]
    assert core.sweep_gate(items, TURNS) == []


def test_gate_drops_unknown_types_and_empty_statements():
    core = load_core()
    items = [{"type": "vibe", "statement": "x", "quote": "let's use SQLite", "line": 3},
             {"type": "decision", "statement": " ", "quote": "let's use SQLite", "line": 3},
             "garbage", {"type": "decision"}]
    assert core.sweep_gate(items, TURNS) == []


def test_gate_dedupes_the_same_quote():
    core = load_core()
    item = {"type": "decision", "statement": "SQLite.", "quote": "let's use SQLite", "line": 3}
    assert len(core.sweep_gate([item, dict(item, statement="SQLite chosen.")], TURNS)) == 1


